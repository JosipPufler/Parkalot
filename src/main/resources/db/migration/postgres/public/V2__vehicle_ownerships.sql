create table if not exists vehicle_ownerships
(
    id                   bigint generated by default as identity
        primary key,
    ownership_end_date   date,
    ownership_start_date date    not null,
    primary_owner        boolean not null,
    user_id              bigint  not null
        constraint fkjclmfetdc5mysyf0b8x64q7fw
            references users,
    vehicle_id           bigint  not null
        constraint fk2nwqam1n98r0t73rn5r117ya6
            references vehicles,
    constraint uc_vehicle_ownership
        unique (user_id, vehicle_id)
);

alter table vehicle_ownerships
    owner to postgres;

grant select, update, usage on sequence vehicle_ownerships_id_seq to anon;

grant select, update, usage on sequence vehicle_ownerships_id_seq to authenticated;

grant select, update, usage on sequence vehicle_ownerships_id_seq to service_role;

grant delete, insert, references, select, trigger, truncate, update on vehicle_ownerships to anon;

grant delete, insert, references, select, trigger, truncate, update on vehicle_ownerships to authenticated;

grant delete, insert, references, select, trigger, truncate, update on vehicle_ownerships to service_role;

do
$$
    begin
        if to_regclass('public.user_vehicles') is not null then
            insert into vehicle_ownerships (user_id, vehicle_id, ownership_start_date, primary_owner)
            select uv.user_id,
                   uv.vehicle_id,
                   current_date,
                   uv.user_id = min(uv.user_id) over (partition by uv.vehicle_id)
            from (select distinct user_id, vehicle_id from user_vehicles) uv
            on conflict on constraint uc_vehicle_ownership do nothing;

            drop table user_vehicles;
        end if;
    end
$$;
